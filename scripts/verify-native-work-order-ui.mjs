import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(new URL('../build/native-ui-test-tools/package.json', import.meta.url))
const { chromium } = require('playwright')
const browser = await chromium.connectOverCDP('http://127.0.0.1:9224')
const page = browser.contexts()[0].pages().find((item) => item.url() === 'app://netcatty/index.html')
assert.ok(page, '未找到 Netcatty 测试窗口')
page.setDefaultTimeout(12000)
const pageErrors = []
page.on('pageerror', (error) => pageErrors.push(error.message))

const openWorkOrder = async (width, height) => {
  await page.setViewportSize({ width, height })
  await page.reload()
  await page.locator('[data-tab-id="cmdb"]').click()
  await page.locator('[data-section="cmdb-sidebar"]').getByRole('button', { name: '工单与统计' }).click()
  await page.getByRole('heading', { name: '受理信息' }).waitFor()
}

try {
  await openWorkOrder(1536, 824)
  await page.getByRole('heading', { name: '新建工单' }).waitFor()
  const header = page.locator('[data-section="cmdb-operations-header"]')
  const modeButton = header.getByRole('button', { name: '新建工单', exact: true })
  const headerSearch = header.getByPlaceholder('搜索工单号或主题')
  await modeButton.waitFor()
  const modeBox = await modeButton.boundingBox()
  const searchBox = await headerSearch.boundingBox()
  assert.ok(modeBox && searchBox && modeBox.x + modeBox.width < searchBox.x && Math.abs(modeBox.y - searchBox.y) < 2, '新建工单按钮应在搜索框左侧且位于同一行')
  await modeButton.click()
  await page.locator('[data-work-order-mode-option="stats"]').click()
  await page.getByRole('table').waitFor()
  await modeButton.click()
  const createMenuItem = page.locator('[data-work-order-mode-option="create"]')
  await createMenuItem.waitFor()
  await createMenuItem.click()
  await page.getByRole('heading', { name: '受理信息' }).waitFor()
  await page.locator('[data-work-order-list]').waitFor()
  await page.locator('[data-work-order-editor]').waitFor()
  const listBox = await page.locator('[data-work-order-list]').boundingBox()
  const editorBox = await page.locator('[data-work-order-editor]').boundingBox()
  assert.ok(listBox && editorBox && listBox.x + listBox.width <= editorBox.x + 2, '宽窗口应为左列表、右表单')
  const topHeader = await page.locator('[data-section="cmdb-operations-header"]').boundingBox()
  const listHeader = await page.locator('[data-work-order-list] > header').boundingBox()
  const editorHeader = await page.locator('[data-work-order-editor] > header').boundingBox()
  assert.ok(topHeader && listHeader && editorHeader && topHeader.y + topHeader.height <= listHeader.y + 2 && Math.abs(listHeader.y - editorHeader.y) < 2, '顶部工具栏及双栏标题应与组织页保持同一层级')
  await page.getByLabel('选择日期').waitFor()
  await page.getByPlaceholder('搜索工单号或主题').waitFor()
  const submit = page.getByRole('button', { name: '创建工单' })
  const before = await submit.boundingBox()
  assert.ok(before && before.y + before.height <= 824, '提交按钮在首屏之外')

  const scroll = page.locator('[data-work-order-scroll]')
  await scroll.evaluate((element) => { element.scrollTop = element.scrollHeight })
  const bottom = await submit.boundingBox()
  assert.ok(bottom && Math.abs(bottom.y - before.y) < 2, '滚动表单时提交栏不应移动')
  await page.getByRole('button', { name: '选择附件' }).waitFor()

  const bubble = page.getByRole('button', { name: '筛选关联资源' })
  const bubbleBox = await bubble.boundingBox()
  const formBox = await page.locator('#cmdb-work-order-form').boundingBox()
  assert.ok(bubbleBox && formBox && bubbleBox.x + bubbleBox.width <= formBox.x + formBox.width, '关联资源入口应贴近表单')
  await bubble.click()
  await page.getByRole('button', { name: '基础设施', exact: true }).last().click()
  await page.getByPlaceholder('搜索关联资源').fill('核心')
  const candidate = page.getByRole('checkbox').first()
  await candidate.check()
  await page.getByText(/已关联 1 项/).waitFor()
  await page.keyboard.press('Escape')
  await page.locator('input[type="file"][data-work-order-attachments]').setInputFiles([
    { name: 'work-order-check.txt', mimeType: 'text/plain', buffer: Buffer.from('attachment before submit') },
    { name: 'work-order-second.txt', mimeType: 'text/plain', buffer: Buffer.from('second attachment') },
  ])
  await page.getByText('work-order-check.txt').waitFor()
  await page.getByText('work-order-second.txt').waitFor()
  const subject = `桌面工单验收 ${Date.now()}`
  await page.getByLabel('工单主题').fill(subject)
  await page.screenshot({ path: fileURLToPath(new URL('../build/native-ui-preview/work-order-form-bottom.png', import.meta.url)) })
  await scroll.evaluate((element) => { element.scrollTop = 0 })
  await page.screenshot({ path: fileURLToPath(new URL('../build/native-ui-preview/work-order-single-page.png', import.meta.url)) })

  await submit.click()
  const row = page.locator('[data-work-order-list] button[aria-pressed]').filter({ hasText: subject })
  await row.waitFor()
  await row.click()
  await page.getByRole('heading', { name: '工单详情' }).waitFor()
  await page.getByText('work-order-check.txt').waitFor()
  await page.getByText('work-order-second.txt').waitFor()
  assert.equal(await page.getByText('保存工单后可上传附件').count(), 0)

  await page.getByRole('button', { name: '新建工单' }).last().click()
  const draft = `未提交草稿 ${Date.now()}`
  await page.getByLabel('工单主题').fill(draft)
  await row.click()
  await page.getByRole('button', { name: '新建工单' }).last().click()
  assert.equal(await page.getByLabel('工单主题').inputValue(), draft, '查看记录覆盖了未提交草稿')

  await page.getByRole('button', { name: '前一天' }).click()
  assert.equal(await row.count(), 0, '前一天仍显示今天的工单')
  await page.getByRole('button', { name: '后一天' }).click()
  await row.waitFor()
  await page.getByPlaceholder('搜索工单号或主题').fill(subject)
  await page.getByPlaceholder('搜索工单号或主题').press('Enter')
  await row.waitFor()
  assert.equal(await page.locator('[data-work-order-list] button[aria-pressed]').count(), 1, '关键词未筛选列表')
  await page.locator('[data-work-order-list]').getByRole('button', { name: '更多筛选' }).click()
  await page.getByRole('dialog').getByLabel('工单类别').waitFor()
  await page.keyboard.press('Escape')

  await page.setViewportSize({ width: 960, height: 768 })
  await page.getByText('工单已创建').waitFor({ state: 'hidden' })
  const narrowSubmit = await submit.boundingBox()
  assert.ok(narrowSubmit && narrowSubmit.y + narrowSubmit.height <= 768, '窄窗口提交按钮不可见')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true, '窄窗口出现横向溢出')
  await page.screenshot({ path: fileURLToPath(new URL('../build/native-ui-preview/work-order-single-page-narrow.png', import.meta.url)) })
  await page.getByRole('button', { name: '工单列表', exact: true }).click()
  await row.waitFor()
  await row.click()
  await page.getByRole('heading', { name: '工单详情' }).waitFor()
  await page.locator('[data-work-order-mobile-new]').click()
  assert.equal(await page.getByLabel('工单主题').inputValue(), draft, '窄窗口切换后草稿丢失')
  await page.setViewportSize({ width: 1536, height: 824 })
  await modeButton.click()
  await page.locator('[data-work-order-mode-option="stats"]').click()
  await page.getByRole('table').waitFor()
  const statsSearch = page.getByPlaceholder('搜索工单号或主题')
  await statsSearch.fill(subject)
  await statsSearch.press('Enter')
  await page.getByRole('row').filter({ hasText: subject }).waitFor()
  assert.equal(await page.locator('tbody tr').count(), 1, '统计页顶部搜索未筛选表格')
  await page.getByRole('button', { name: '清除工单搜索' }).click()
  await page.screenshot({ path: fileURLToPath(new URL('../build/native-ui-preview/work-order-statistics.png', import.meta.url)) })
  await modeButton.click()
  await page.locator('[data-work-order-mode-option="create"]').click()
  assert.equal(await page.getByLabel('工单主题').inputValue(), draft, '切换统计后草稿丢失')
  await page.setViewportSize({ width: 480, height: 768 })
  assert.equal(await page.locator('[data-cmdb-native]').evaluate((element) => element.scrollWidth <= element.clientWidth), true, '紧凑窗口的 Cmdb 区域出现横向溢出')
  await page.screenshot({ path: fileURLToPath(new URL('../build/native-ui-preview/work-order-compact.png', import.meta.url)) })
  await page.setViewportSize({ width: 1536, height: 824 })
  await page.locator('[data-work-order-editor]').getByRole('button', { name: '清空' }).click()
  await page.getByPlaceholder('搜索工单号或主题').fill('')
  await page.screenshot({ path: fileURLToPath(new URL('../build/native-ui-preview/work-order-ready.png', import.meta.url)) })
  await page.locator('[data-section="cmdb-sidebar"]').getByRole('button', { name: 'IPAM/IP' }).click()
  const ipamHeader = page.locator('[data-section="cmdb-ipam-header"]')
  await ipamHeader.getByPlaceholder('搜索 IP、资产、人员、部门、VLAN 或 VNI').waitFor()
  const ipamAdd = ipamHeader.locator('[data-ipam-add-subnet]')
  const ipamSearch = ipamHeader.locator('[data-ipam-search]')
  const ipamAddBox = await ipamAdd.boundingBox()
  const ipamSearchBox = await ipamSearch.boundingBox()
  assert.ok(ipamAddBox && ipamSearchBox && ipamAddBox.x + ipamAddBox.width < ipamSearchBox.x && Math.abs(ipamAddBox.y - ipamSearchBox.y) < 2, 'IPAM 新增网段按钮应在搜索框左侧且位于同一行')
  await page.locator('[data-section="cmdb-sidebar"]').getByRole('button', { name: '组织架构' }).click()
  const peopleHeader = page.locator('[data-section="cmdb-people-header"]')
  await peopleHeader.getByPlaceholder('搜索姓名、人员编号、职务或联系电话').waitFor()
  const peopleAdd = peopleHeader.locator('[data-people-add]')
  const peopleSearch = peopleHeader.locator('[data-people-search]')
  const peopleAddBox = await peopleAdd.boundingBox()
  const peopleSearchBox = await peopleSearch.boundingBox()
  assert.ok(peopleAddBox && peopleSearchBox && peopleAddBox.x + peopleAddBox.width < peopleSearchBox.x && Math.abs(peopleAddBox.y - peopleSearchBox.y) < 2, '组织架构新增人员按钮应在搜索框左侧且位于同一行')
  assert.deepEqual(pageErrors, [], '桌面页面发生运行时异常')
  console.log('桌面工单、IPAM/IP、组织架构顶部布局及工单交互检查通过')
} finally {
  await browser.close()
}
